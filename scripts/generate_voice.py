from pathlib import Path
from gtts import gTTS

TEXT = (
    "Представь, ты тираннозавр. Самый страшный хищник своего времени. "
    "Тринадцать метров длины, огромная голова, зубы размером с банан. "
    "Тебе кажется, что ты король этой планеты. Но есть нюанс. "
    "Ты не самый быстрый динозавр, и тебе не нужно гоняться за всем подряд. "
    "Твоя сила — внезапная атака, мощные челюсти и умение разорвать добычу. "
    "А хвост? Это не декорация. Он помогает удерживать баланс, пока массивное тело движется. "
    "Но вокруг полно опасностей: болезни, травмы, конкуренты, голод. "
    "А потом, примерно шестьдесят шесть миллионов лет назад, прилетает астероид. "
    "Пожары, пыль в атмосфере, резкое похолодание, рушатся пищевые цепочки. "
    "Ты можешь быть огромным, зубастым и чертовски сильным. "
    "Но когда ломается весь мир вокруг, мышцы уже ничего не решают. "
    "И вот так закончилась эпоха тираннозавров. Не в драке. Из-за космического камня."
)
def main():
    Path("public").mkdir(parents=True, exist_ok=True)
    output = Path("public/voice.mp3")
    gTTS(text=TEXT, lang="ru", tld="com", slow=False, timeout=15).save(str(output))
    if not output.exists() or output.stat().st_size < 10000:
        raise RuntimeError("gTTS returned an empty or invalid audio file.")
    print(f"VOICE_OK provider=gTTS bytes={output.stat().st_size}")
if __name__ == "__main__":
    main()
